"""List the open-source packages ComicK Tools uses, with versions and licences.

Reads the tools' requirements files and the web interface's package.json and
package-lock.json, so the list is always what is actually installed.

    python legal/packages.py           print the list
    python legal/packages.py --write   update legal/packages.txt
    python legal/packages.py --json    the same data as JSON, for the web UI
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UI = ROOT / "ui"
OUT = ROOT / "legal" / "packages.txt"
PYTHON_MIN = "3.8"


def python_packages():
    """Non-comment lines from every tool's requirements.txt, deduplicated."""
    seen = {}
    for req in sorted((ROOT / "tools").glob("*/*/requirements.txt")):
        for line in req.read_text(encoding="utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                seen.setdefault(line, []).append(req.parent.name)
    return [{"spec": spec, "usedBy": tools} for spec, tools in seen.items()]


def ui_packages():
    manifest = json.loads((UI / "package.json").read_text(encoding="utf-8"))
    try:
        lock = json.loads((UI / "package-lock.json").read_text(encoding="utf-8")).get("packages", {})
    except FileNotFoundError:
        lock = {}

    def describe(names):
        rows = []
        for name in sorted(names):
            entry = lock.get("node_modules/" + name, {})
            rows.append({
                "name": name,
                "version": entry.get("version") or names[name],
                "license": entry.get("license") or "see the package",
            })
        return rows

    runtime = manifest.get("dependencies", {})
    build = manifest.get("devDependencies", {})
    direct = set(runtime) | set(build)
    # Only installed packages, not the lockfile's own root entry.
    indirect = [k for k in lock if k.startswith("node_modules/") and k[len("node_modules/"):] not in direct]
    return {"runtime": describe(runtime), "build": describe(build), "indirect": len(indirect)}


def collect():
    return {"python": {"minimum": PYTHON_MIN, "packages": python_packages()}, "ui": ui_packages()}


def as_text(data):
    lines = [
        "ComicK Tools",
        "Open-source software",
        "",
        "Generated by legal/packages.py from the requirements files and",
        "ui/package-lock.json. Run it again with --write after changing any",
        "dependency. The web interface shows the same list, always current.",
        "",
        "1. Python tools",
        "",
        "- Python " + PYTHON_MIN + " or newer (PSF-2.0)",
    ]
    py = data["python"]["packages"]
    if py:
        for p in py:
            lines.append("- " + p["spec"] + ", used by " + ", ".join(p["usedBy"]))
    else:
        lines.append("- Standard library only, no other packages")

    def section(number, title, rows):
        lines.extend(["", str(number) + ". " + title, ""])
        for r in rows:
            lines.append("- " + r["name"] + " " + r["version"] + " (" + r["license"] + ")")

    section(2, "Web interface, at runtime", data["ui"]["runtime"])
    section(3, "Web interface, to build it", data["ui"]["build"])
    lines.extend([
        "",
        "4. Everything else",
        "",
        "The packages above depend on " + str(data["ui"]["indirect"]) + " further packages, listed with",
        "their exact versions and licences in ui/package-lock.json.",
        "",
        "Each package is licensed under its own terms. Nothing in our Terms of",
        "Service limits your rights under those licences.",
    ])
    return "\n".join(lines) + "\n"


def main():
    data = collect()
    if "--json" in sys.argv:
        print(json.dumps(data))
    elif "--write" in sys.argv:
        # Bytes, so Windows doesn't turn the newlines into CRLF.
        OUT.write_bytes(as_text(data).encode("utf-8"))
        print("Wrote " + str(OUT.relative_to(ROOT)))
    else:
        sys.stdout.write(as_text(data))


if __name__ == "__main__":
    main()
